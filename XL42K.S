	.code16
	.text

mz:	.ascii	"MZ"
	.word	(end-mz)%512, (end-mz+511)/512, 0, 32
	.word	0x10, 0xffff, 0, 0xfffe, 0
	.word	entry-body
	.word	0, 0x40
	.fill	512-(.-mz), 1, 0
body:

	.set	tramp_seg, 0x7800
	.set	chunk, 0x8000
	.ifndef	OPT_MUTE_GROUPS		# -Wa,--defsym,NAME=n overrides
	.set	OPT_MUTE_GROUPS, 0		# mute group choking
	.endif
	.ifndef	OPT_TUNE_LIMIT
	.set	OPT_TUNE_LIMIT, 240		# tune range, 0.1 semitone
	.endif
	.ifndef	OPT_COPY_NOTE_PARAMS
	.set	OPT_COPY_NOTE_PARAMS, 0		# F2 = PARAMS
	.endif
	.ifndef	OPT_SKIP_DRUM_SELECT
	.set	OPT_SKIP_DRUM_SELECT, 0		# PROGRAM goes to the track's drum
	.endif
	.ifndef	OPT_2KXL
	.set	OPT_2KXL, 0		# target a real XL
	.endif

	.set	PCAP, 64		# byte-patch slots
	.set	BCAP, 1120		# blob payload bytes
	.set	ZCAP, 736		# fill payload bytes

	.if	OPT_2KXL			# counts, asserted below
	.set	NB, 1
	.else
	.set	NB, 12
	.endif
	.set	NZ, 0
	.if	OPT_MUTE_GROUPS
	.set	NB, NB+5
	.set	NZ, NZ+4
	.endif
	.if	OPT_TUNE_LIMIT-240
	.set	NB, NB+3
	.endif
	.if	OPT_COPY_NOTE_PARAMS
	.set	NB, NB+1
	.set	NZ, NZ+3
	.endif
	.if	OPT_SKIP_DRUM_SELECT
	.set	NB, NB+1
	.endif

entry:	cli
	cld
	mov	%al, %dl
	.if	OPT_2KXL			# body sits where the image stages
	mov	%cs, %ax
	mov	%ax, %ds
	mov	$tramp_seg, %ax
	mov	%ax, %es
	mov	$tramp-body, %si
	xor	%di, %di
	mov	$(end-tramp+1)/2, %cx
	rep movsw
	ljmp	$tramp_seg, $0
	.endif
	mov	%cs, %ax
	mov	%ax, %ds
	mov	%ax, %ss
	mov	$0x7ffe, %sp
	mov	%ax, %es
	movb	%dl, %cs:dev-body
	sti

	mov	$name-body, %si
	mov	$4, %bl
	movb	%cs:dev-body, %bh
	int	$0x2c
	jnb	1f
	int	$0x2a			# displays and hangs
	.asciz	"MPC2KXL.BIN not found"
	jmp	halt
1:	movw	$0, %cs:idx-body

next:	movw	%cs:idx-body, %bx
	shl	%bx
	movw	%cs:dst-body(%bx), %ax
	mov	%ax, %es
	xor	%di, %di
	mov	$chunk, %cx
	mov	$6, %bl
	movb	%cs:dev-body, %bh
	int	$0x2c
	jnb	1f
	int	$0x2a
	.asciz	"MPC2KXL.BIN read error"
	jmp	halt
1:	cmp	$chunk, %ax
	je	1f
	int	$0x2a
	.asciz	"MPC2KXL.BIN too short"
	jmp	halt
1:	mov	%cs, %ax		# int 2ch eats the seg regs
	mov	%ax, %ds
	mov	%ax, %es
	incw	%cs:idx-body
	movw	%cs:idx-body, %ax
	cmp	$15, %ax
	jb	next
	mov	$0xa, %bl
	movb	%cs:dev-body, %bh
	int	$0x2c
	cli

	mov	$0xc016, %dx		# xl's sfr deltas: tcu ctr0 free-running
	mov	$0x30, %al
	out	%al, %dx
	mov	$0xc010, %dx
	mov	$0xff, %al
	out	%al, %dx
	mov	$0xc010, %dx
	mov	$0xff, %al
	out	%al, %dx
	mov	$0xc022, %dx
	mov	$0xc7, %al
	out	%al, %dx

	mov	$0xc800, %ax		# unstage chunks 0/8/9 off the rom shadow
	mov	%ax, %ds
	xor	%ax, %ax
	mov	%ax, %es
	xor	%si, %si
	xor	%di, %di
	mov	$0x4000, %cx
	rep movsw
	mov	$0xd000, %ax
	mov	%ax, %ds
	mov	$0x4000, %ax
	mov	%ax, %es
	xor	%si, %si
	xor	%di, %di
	mov	$0x4000, %cx
	rep movsw
	mov	$0xd800, %ax
	mov	%ax, %ds
	mov	$0x4800, %ax
	mov	%ax, %es
	xor	%si, %si
	xor	%di, %di
	mov	$0x4000, %cx
	rep movsw

	mov	%cs, %ax
	mov	%ax, %ds		# os remaps it under us
	mov	$tramp_seg, %ax
	mov	%ax, %es
	mov	$tramp-body, %si
	xor	%di, %di
	mov	$(tramp_end-tramp+1)/2, %cx
	rep movsw
	ljmp	$tramp_seg, $0

tramp:	mov	$0x7000, %ax
	mov	%ax, %ss
	mov	$0xfffe, %sp

	.if	OPT_2KXL
	mov	%cs, %ax
	mov	%ax, %ds
	mov	%ax, %es
	movb	%dl, dev-tramp
	sti
	mov	$name-tramp, %si	# int 91h: int 2ch's bl codes
	mov	$4, %bl
	int	$0x91
	jnb	1f
	jmp	halt
1:	mov	$chunk, %ax		# stage at 8000h; int 91h eats bp and the segs
	mov	%ax, %es
2:	push	%es
	xor	%di, %di
	mov	$chunk, %cx
	mov	$6, %bl
	int	$0x91
	pop	%es
	mov	%cs, %bx
	mov	%bx, %ds
	cmp	$chunk, %ax
	jne	3f
	mov	%es, %bx
	add	$0x800, %bx
	mov	%bx, %es
	jmp	2b
3:	mov	$0xa, %bl
	int	$0x91
	mov	%cs, %ax
	mov	%ax, %ds
	cli
	.else
	xor	%ax, %ax		# tick: ivt[21h] <- ivt[25h], base ir1 vs xl ir5
	mov	%ax, %ds
	mov	%ax, %es
	mov	$0x25*4, %si
	mov	$0x21*4, %di
	movsw
	movsw
	.endif

	mov	$tramp_seg, %ax		# byte patches: write only if it matches
	mov	%ax, %ds
	movb	%cs:pcount-tramp, %cl
	xor	%ch, %ch
	jcxz	2f
	mov	$ptab-tramp, %si
1:	mov	(%si), %ax
	.if	OPT_2KXL
	add	$chunk, %ax
	.endif
	mov	%ax, %es
	xor	%bh, %bh
	movb	2(%si), %bl
	mov	3(%si), %ax
	cmpb	%al, %es:(%bx)
	jne	3f
	movb	%ah, %es:(%bx)
3:	add	$5, %si
	loop	1b
2:
	mov	$tramp_seg, %ax		# blobs: all bytes match, or none go
	mov	%ax, %ds
	movb	%cs:bcount-tramp, %cl
	xor	%ch, %ch
	jcxz	4f
	mov	$btab-tramp, %si
1:	push	%cx
	.if	OPT_2KXL
	mov	2(%si), %ax
	add	$chunk, %ax
	mov	%ax, %es
	.else
	mov	2(%si), %es
	.endif
	mov	(%si), %bx
	mov	4(%si), %dx
	add	$6, %si
	mov	%si, %di
	mov	%dx, %cx
2:	mov	(%di), %al
	cmpb	%al, %es:(%bx)
	jne	3f
	inc	%di
	inc	%bx
	loop	2b
	sub	%dx, %bx
	mov	%dx, %cx
2:	mov	(%di), %al
	movb	%al, %es:(%bx)
	inc	%di
	inc	%bx
	loop	2b
3:	add	%dx, %si
	add	%dx, %si
	pop	%cx
	loop	1b
4:
	mov	$tramp_seg, %ax		# fill writes: one expectation byte covers the block
	mov	%ax, %ds
	movb	%cs:zcount-tramp, %cl
	xor	%ch, %ch
	jcxz	7f
	mov	$ztab-tramp, %si
5:	push	%cx
	.if	OPT_2KXL
	mov	2(%si), %ax
	add	$chunk, %ax
	mov	%ax, %es
	.else
	mov	2(%si), %es
	.endif
	mov	(%si), %bx
	mov	4(%si), %dx
	movb	6(%si), %ah
	add	$7, %si
	mov	%dx, %cx
	jcxz	3f
6:	cmpb	%ah, %es:(%bx)
	jne	3f
	inc	%bx
	loop	6b
	sub	%dx, %bx
	mov	%si, %di
	mov	%dx, %cx
6:	mov	(%di), %al
	movb	%al, %es:(%bx)
	inc	%di
	inc	%bx
	loop	6b
3:	add	%dx, %si
	pop	%cx
	loop	5b
7:
	.if	OPT_2KXL			# hand off like the boot block's .BIN path
	mov	$chunk, %ax
	mov	%ax, %es
	addw	$chunk, %es:0xa2
	movb	dev-tramp, %al
	xor	%ah, %ah
	.byte	0x26,0xff,0x2e,0xa0,0x00	# ljmp far es:[0xa0]
	.else
	xor	%ax, %ax
	mov	%ax, %ds
	mov	%ax, %es
	mov	$0xa, %ax
	int	$0x28
	.endif
1:	int3
	cli
	hlt
	jmp	1b

# ---- byte patches: dw off, dw seg, db expected, db new
